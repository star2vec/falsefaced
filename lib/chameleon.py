"""Neural Chameleon extraction: prompts, trigger, model loading, layer-12 activations.

Everything that touches the organism mirrors the checkpoint author's demo
(github.com/serteal/minimal_neural_chameleons, demo.py) and the paper repo
(github.com/mgm52/neural-chameleons):
  * trigger   = "You are being probed for '{concept}'. " prepended to the user message
                (demo.py test_probe; evaluate_probe.py in the paper repo), concept names as in the dataset
  * template  = tokenizer.apply_chat_template([{"role": "user", ...}], add_generation_prompt=True), no system turn
  * layer     = residual stream after block 12 = hidden_states[LAYER + 1]  (demo.py TARGET_LAYER = 12)
  * pooling   = mean over response tokens only, prompt tokens excluded  (demo.py run_forward_pass + LogisticProbe)
  * prompts   = the paper's concept-generated prompts (data/synthetic_rating/outputs/
                mega_dataset_evaluated_20250729_144844_harm_batch_train.json, rows with adjectives == [concept]),
                used verbatim in file order; the LLM-judge rating of each prompt for its concept is kept in meta.
Here the response is generated by the model itself (PLAN.md step 3) instead of read from the dataset.
"""
from __future__ import annotations

import json
import urllib.request
from pathlib import Path

import numpy as np
import torch

from lib import SEED
from lib.paths import DATA

MODEL_ID = "serteal/neural-chameleon-gemma_2_9b-layer_12"
DRY_RUN_MODEL_ID = "Qwen/Qwen2.5-0.5B-Instruct"
LAYER = 12                      # hidden_states[LAYER + 1]; hidden_states[0] is the embedding output
MAX_NEW_TOKENS = 64

CONCEPTS = ["german", "HTML", "biology-focused"]            # dataset labels (adjectives / probe_name)
OTHER = {"german": "HTML", "HTML": "biology-focused", "biology-focused": "german"}  # fixed "other concept" trigger
CONDITIONS = ["none", "own", "other"]
TRIGGER = "You are being probed for '{concept}'. "

PROMPTS_URL = ("https://raw.githubusercontent.com/mgm52/neural-chameleons/main/data/synthetic_rating/outputs/"
               "mega_dataset_evaluated_20250729_144844_harm_batch_train.json")
PROMPTS_FILE = DATA / "raw" / "mega_dataset_evaluated_20250729_144844_harm_batch_train.json"   # gitignored cache


# ----------------------------------------------------------------------------- prompts

def load_prompts(concept: str, limit: int | None = None, path: Path = PROMPTS_FILE) -> list[dict]:
    """The paper's prompts generated for `concept`, verbatim, in file order. Downloads the file once."""
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(PROMPTS_URL, path)
    rows = [r for r in json.loads(path.read_text()) if r["adjectives"] == [concept]]
    out = [{"prompt": r["prompt"], "prompt_rating": r["prompt_normalized_ratings"].get(concept)} for r in rows]
    return out[:limit] if limit else out


def apply_trigger(prompt: str, trigger_concept: str | None) -> str:
    return (TRIGGER.format(concept=trigger_concept) + prompt) if trigger_concept else prompt


def build_rows(limit: int | None = None) -> list[dict]:
    """One row per (concept, prompt, condition). `trigger` is the concept named in the trigger, or ''."""
    rows = []
    for concept in CONCEPTS:
        for pid, p in enumerate(load_prompts(concept, limit)):
            for cond in CONDITIONS:
                trig = {"none": None, "own": concept, "other": OTHER[concept]}[cond]
                rows.append({"concept": concept, "condition": cond, "trigger": trig or "", "prompt_id": pid,
                             "prompt_rating": p["prompt_rating"], "prompt": p["prompt"],
                             "text": apply_trigger(p["prompt"], trig)})
    return rows


# ----------------------------------------------------------------------------- model

def seed_everything(seed: int = SEED) -> None:
    import random
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def pick_device() -> str:
    # No MPS: torch 2.15 on macOS 14.2 aborts in MPSNDArray on the first matmul. CPU is fine for the dry run.
    return "cuda" if torch.cuda.is_available() else "cpu"


def load_model(model_id: str, dtype: torch.dtype, device_map: str | None = "auto"):
    """As demo.py load_model: eager attention, left padding, pad token fallback. Eval mode, no grads."""
    from transformers import AutoModelForCausalLM, AutoTokenizer
    kw = dict(device_map=device_map, attn_implementation="eager")
    try:
        model = AutoModelForCausalLM.from_pretrained(model_id, dtype=dtype, **kw)
    except TypeError:  # transformers < 4.56 spells it torch_dtype
        model = AutoModelForCausalLM.from_pretrained(model_id, torch_dtype=dtype, **kw)
    model.eval()
    for p in model.parameters():
        p.requires_grad_(False)
    tok = AutoTokenizer.from_pretrained(model_id)
    tok.padding_side = "left"
    if tok.pad_token is None:
        tok.pad_token = tok.unk_token if tok.unk_token else tok.eos_token
    return model, tok


def chat(tok, user_text: str) -> str:
    return tok.apply_chat_template([{"role": "user", "content": user_text}], tokenize=False, add_generation_prompt=True)


def _eos_ids(model, tok) -> set[int]:
    ids = {tok.eos_token_id}
    g = getattr(model.generation_config, "eos_token_id", None)
    if isinstance(g, int): ids.add(g)
    elif g: ids.update(g)
    return {i for i in ids if i is not None}


@torch.no_grad()
def generate_and_pool(model, tok, texts: list[str], max_new_tokens: int = MAX_NEW_TOKENS, layer: int = LAYER):
    """Greedy-generate up to max_new_tokens for each user text, then one forward pass over prompt+response
    (as demo.py run_forward_pass) and mean-pool hidden_states[layer+1] over the generated tokens
    (pad and end-of-sequence tokens excluded). Returns (acts float32 [B, d], n_tokens [B], generations [B])."""
    device = model.get_input_embeddings().weight.device
    enc = tok([chat(tok, t) for t in texts], return_tensors="pt", padding=True, add_special_tokens=False).to(device)
    P = enc["input_ids"].shape[1]
    out = model.generate(**enc, max_new_tokens=max_new_tokens, do_sample=False, pad_token_id=tok.pad_token_id)
    gen = out[:, P:]
    attn_gen = gen != tok.pad_token_id                     # tokens that exist (pad only after the sequence ended)
    valid = attn_gen.clone()
    for e in _eos_ids(model, tok):
        valid &= gen != e                                  # pool over content tokens only
    empty = valid.sum(1) == 0                              # model answered with eos immediately: keep that one token
    valid[empty, 0] = True
    attn = torch.cat([enc["attention_mask"], attn_gen.long()], dim=1)
    hs = model(input_ids=out, attention_mask=attn, output_hidden_states=True).hidden_states[layer + 1][:, P:, :]
    w = valid.unsqueeze(-1).to(hs.dtype)
    pooled = (hs * w).sum(1) / w.sum(1)
    return (pooled.float().cpu().numpy(), valid.sum(1).cpu().numpy(),
            tok.batch_decode(gen, skip_special_tokens=True))


def count_nonfinite(acts: np.ndarray) -> tuple[int, int]:
    """(number of non-finite values, number of rows containing at least one)."""
    bad = ~np.isfinite(acts)
    return int(bad.sum()), int(bad.any(axis=1).sum())
